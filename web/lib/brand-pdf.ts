export function drawBrandSignature(doc: jsPDF, x: number, y: number, width: number) {
  const scale = width / ART_WIDTH;
  doc.saveGraphicsState();
  doc.setFillColor(GRANATE);
  doc.setDrawColor(GRANATE);
  doc.setLineCap('round');
  doc.setLineJoin('round');

  for (const shape of signature) {
    const path = shape.points.map(([op, ...coordinates]) => ({
      op,
      c: coordinates.map((value, index) => value * scale + (index % 2 === 0 ? x : y)),
    }));
    doc.path(path);
    if (shape.stroke) {
      doc.setLineWidth(shape.stroke * scale);
      doc.stroke();
    } else {
      doc.fillEvenOdd();
    }
  }

  doc.restoreGraphicsState();
}
