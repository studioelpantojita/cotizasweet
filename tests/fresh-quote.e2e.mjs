// Fresh-form regression: no seeded quote or draft, only UI entry and explicit actions.
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {mkdirSync,writeFileSync,readFileSync} from 'node:fs';
import {createHash,randomUUID} from 'node:crypto';

const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const origin=process.env.E2E_ORIGIN||'http://127.0.0.1:3370';
assert.ok(/^http:\/\/(127\.0\.0\.1|localhost):\d+$/.test(origin),'Synthetic fresh-form test is restricted to loopback');
const {accounts}=JSON.parse(readFileSync(process.env.E2E_CREDENTIALS_FILE||resolve(root,'.local/review-accounts.json'),'utf8'));
const customer=accounts.find(account=>account.role==='customer'&&account.username&&account.password);
assert.ok(customer,'Private customer review credentials required');
const require=createRequire(resolve(root,'web/package.json'));
const {chromium}=require('playwright');
const out=resolve(root,'tests/artifacts/fresh-quote');mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true,...(process.env.E2E_BROWSER_CHANNEL?{channel:process.env.E2E_BROWSER_CHANNEL}:{})});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage();page.setDefaultTimeout(30000);
await page.emulateMedia({reducedMotion:'reduce'});
const checks=[],errors=[];
let firstId='',updatedId='',firstHash='',receiptId='';
page.on('pageerror',error=>errors.push(error.message));
const check=(name,condition)=>{assert.ok(condition,name);checks.push(name);};
const sha256=bytes=>createHash('sha256').update(bytes).digest('hex');
const step=async index=>{await page.getByRole('navigation',{name:'Pasos de la cotización'}).getByRole('button').nth(index).click();await page.locator('#quote-step-'+index).waitFor({state:'visible'});};
const savedResponse=()=>page.waitForResponse(response=>new URL(response.url()).pathname==='/api/quotes'&&response.request().method()==='POST');
async function saveAndDownload(filename){
 const responsePromise=savedResponse(),downloadPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'Guardar y descargar PDF',exact:true}).click();
 const response=await responsePromise,record=await response.json();
 assert.equal(response.status(),201,record.error||'Saved quote response');
 const download=await downloadPromise,path=resolve(out,filename);await download.saveAs(path);
 const bytes=readFileSync(path);assert.equal(bytes.subarray(0,5).toString(),'%PDF-');
 return {record,bytes};
}
try{
 await page.goto(origin+'/auth/login');
 await page.locator('input[name="username"]').fill(customer.username);
 await page.locator('input[name="password"]').fill(customer.password);
 await page.locator('form').getByRole('button',{name:'Acceder',exact:true}).click();
 await page.waitForURL(url=>url.pathname==='/cotizar');
 await page.locator('#project-detail').waitFor({state:'visible'});
 check('New browser context starts with an empty project',await page.locator('#project-detail').inputValue()==='');
 check('New form starts with empty customer identity',await page.locator('#client-document').inputValue()===''&&await page.locator('#client-name').inputValue()==='');
 check('New form starts without package selection',await page.locator('.package-card.is-selected').count()===0);
 const marker=randomUUID().slice(0,8).toUpperCase(),client='Cliente sintético formulario nuevo '+marker;
 const detail='Prueba manual automatizada desde formulario vacío '+marker+'. Celebración con un paquete referencial.';
 await page.locator('#project-detail').fill(detail);
 await page.locator('#client-document').fill('12345678');
 await page.locator('#client-name').fill(client);
 await page.locator('#business-phone').fill('900000000');
 const issued=await page.locator('[data-field="issued"] input').inputValue();
 const date=new Date(issued+'T12:00:00Z');date.setUTCDate(date.getUTCDate()+10);
 await page.locator('[data-field="eventDate"] input').fill(date.toISOString().slice(0,10));
 await page.getByRole('button',{name:'Revisar contenido: Esencial',exact:true}).click();
 check('Opening Essential only reviews the package',await page.getByRole('dialog').isVisible()&&await page.locator('.package-card.is-selected').count()===0);
 await page.getByRole('dialog').getByRole('button',{name:'Elegir este paquete',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('.package-card.is-selected h3')?.textContent==='Esencial');
 check('Explicit confirmation selects Essential',true);
 await step(3);
 const send=page.getByRole('button',{name:'Enviar Cotización',exact:true});
 check('Unstored fresh proposal cannot be sent',await send.isDisabled());
 const first=await saveAndDownload('fresh-quote.pdf');firstId=first.record.id;firstHash=sha256(first.bytes);
 check('Fresh UI input is preserved by the server',first.record.quote.client===client&&first.record.quote.projectBrief===detail);
 check('First save downloads a valid server PDF',first.bytes.length>1000&&typeof firstId==='string');
 await page.waitForFunction(()=>Array.from(document.querySelectorAll('button')).some(button=>button.textContent?.trim()==='Enviar Cotización'&&!button.disabled));
 check('Save enables Send despite normalized property order',await send.isEnabled());
 const archived=await context.request.get(origin+'/api/quotes/'+encodeURIComponent(firstId)+'/pdf');
 assert.equal(archived.status(),200);
 check('Downloaded PDF matches immutable archived bytes',sha256(await archived.body())===firstHash&&archived.headers()['x-document-sha256']===firstHash);
 const sendResponse=page.waitForResponse(response=>new URL(response.url()).pathname==='/api/quotes/'+firstId+'/submit'&&response.request().method()==='POST');
 await send.click();
 const sent=await sendResponse,body=await sent.json();assert.equal(sent.status(),200,body.error||'Submission response');receiptId=body.receipt.id;
 await page.getByRole('status').filter({hasText:'Enviada al administrador'}).waitFor({state:'visible'});
 check('Explicit Send displays administrator receipt',typeof receiptId==='string'&&body.receipt.pdfSha256===firstHash);
 check('Email remains explicitly unconfigured',body.receipt.emailStatus==='not_configured');
 await page.screenshot({path:resolve(out,'fresh-saved-and-sent.png'),fullPage:true});
 await page.getByRole('tab',{name:'Presupuestos guardados'}).click();
 const row=page.locator('.history-row').filter({hasText:client}).filter({hasText:firstId.slice(0,8).toUpperCase()});
 await row.waitFor({state:'visible'});
 check('Freshly saved quote appears in account history',await row.count()===1);
 const historyDownload=page.waitForEvent('download');
 await row.getByRole('button',{name:'Descargar presupuesto de '+client,exact:true}).click();
 const historyPath=resolve(out,'fresh-quote-from-history.pdf');await (await historyDownload).saveAs(historyPath);
 check('History download preserves archived PDF SHA-256',sha256(readFileSync(historyPath))===firstHash);
 await row.getByRole('button',{name:'Abrir',exact:true}).click();
 await page.locator('#project-detail').waitFor({state:'visible'});
 await page.locator('#project-detail').fill(detail+' Ajuste posterior al envío.');
 await step(3);
 check('Editing after Send disables it until another save',await send.isDisabled());
 const updated=await saveAndDownload('fresh-quote-updated.pdf');updatedId=updated.record.id;
 check('Edited proposal creates a new saved snapshot',updatedId!==firstId&&updated.record.quote.projectBrief.endsWith('Ajuste posterior al envío.'));
 await page.waitForFunction(()=>Array.from(document.querySelectorAll('button')).some(button=>button.textContent?.trim()==='Enviar Cotización'&&!button.disabled));
 check('Saving updated proposal re-enables Send',await send.isEnabled());
 const original=await context.request.get(origin+'/api/quotes/'+encodeURIComponent(firstId)+'/pdf');
 check('Earlier sent snapshot remains unchanged',original.status()===200&&sha256(await original.body())===firstHash);
 const updatedReceipt=await context.request.get(origin+'/api/quotes/'+encodeURIComponent(updatedId)+'/submit');
 check('New snapshot is not sent implicitly',updatedReceipt.status()===200&&(await updatedReceipt.json()).receipt===null);
 await page.screenshot({path:resolve(out,'fresh-updated-not-sent.png'),fullPage:true});
 check('Fresh-form flow has no uncaught browser errors',errors.length===0);
 const report={status:'passed',scope:'Fresh empty-form UI; two synthetic saved snapshots in local review customer history, one explicit administrator submission, no external email',origin,checks,errors,firstQuoteId:firstId,updatedQuoteId:updatedId,receiptId,pdfSha256:firstHash};
 writeFileSync(resolve(out,'report.json'),JSON.stringify(report,null,2));
 console.log(JSON.stringify({status:'passed',checks:checks.length,report:resolve(out,'report.json')}));
}catch(error){
 // Do not capture the login form: it may still contain private credentials.
 if(new URL(page.url()).pathname==='/cotizar')await page.screenshot({path:resolve(out,'failure.png'),fullPage:true}).catch(()=>{});
 writeFileSync(resolve(out,'report.json'),JSON.stringify({status:'failed',scope:'Fresh empty-form UI; synthetic local records only',origin,checks,errors,firstQuoteId:firstId,updatedQuoteId:updatedId,error:error.message},null,2));
 throw error;
}finally{await context.close();await browser.close();}
