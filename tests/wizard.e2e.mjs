import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {mkdirSync,writeFileSync} from 'node:fs';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const origin=process.env.E2E_ORIGIN||'http://127.0.0.1:3190';
const require=createRequire(resolve(root,'web/package.json'));
const {chromium}=require('playwright');
const out=resolve(root,'tests/artifacts/wizard-ux');mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true,...(process.env.E2E_BROWSER_CHANNEL?{channel:process.env.E2E_BROWSER_CHANNEL}:{})});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage();page.setDefaultTimeout(20000);
await page.emulateMedia({reducedMotion:'reduce'});
const checks=[],errors=[];
page.on('pageerror',error=>errors.push(error.message));
const check=(name,value)=>{assert.ok(value,name);checks.push(name);};
const step=label=>page.getByRole('navigation',{name:'Pasos de la cotización'}).getByRole('button',{name:new RegExp(label)}).click();
try {
 await page.goto(origin+'/cotizar');
 await page.locator('#client-document').waitFor({state:'visible'});
 check('Four accessible numbered navigation steps',await page.getByRole('navigation',{name:'Pasos de la cotización'}).getByRole('button').count()===4);
 check('Exactly one step visible',await page.locator('.wizard-step:visible').count()===1);
 check('Former project control removed from client section',await page.locator('.client-section [data-field="event"]').count()===0);
 await page.locator('#project-detail').fill('Proyecto sintético para verificar el recorrido por pasos.\nDetalle conservado para el documento.');
 await page.locator('#client-document').fill('12345678');
 await page.locator('#client-name').fill('Cliente sintético de prueba wizard');
 await page.locator('#business-phone').fill('900000000');
 await page.screenshot({path:resolve(out,'paso-1-desktop.png'),fullPage:true});
 await page.getByRole('button',{name:'Continuar',exact:true}).click();
 await page.locator('#quote-step-1').waitFor({state:'visible'});
 check('Continue opens services',true);
 await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
 await page.screenshot({path:resolve(out,'paso-2-desktop.png'),fullPage:true});
 await step('Entrega y condiciones');
 await page.locator('#location-mode').click();
 await page.getByRole('option',{name:/^En locación/}).click();
 await page.locator('[data-field="address"] input').fill('Dirección sintética conservada al volver al paso');
 await page.locator('#location-mode').click();
 await page.getByRole('option',{name:/^Recojo/}).click();
 await step('Servicios e insumos');
 await step('Entrega y condiciones');
 await page.locator('#location-mode').click();
 await page.getByRole('option',{name:/^En locación/}).click();
 check('Delivery draft ref survives step navigation',(await page.locator('[data-field="address"] input').inputValue())==='Dirección sintética conservada al volver al paso');
 await page.locator('#location-mode').click();
 await page.getByRole('option',{name:/^Recojo/}).click();
 await step('Revisar propuesta');
 await page.getByRole('button',{name:'Descargar cotización PDF',exact:true}).click();
 await page.locator('#quote-step-1').waitFor({state:'visible'});
 check('Invalid final action reveals services step',true);
 await page.waitForFunction(()=>document.activeElement?.getAttribute('data-field')==='items');
 check('Invalid field receives focus after reveal',true);
 await step('Proyecto y cliente');
 check('Client values preserved',(await page.locator('#client-name').inputValue())==='Cliente sintético de prueba wizard');
 check('Project detail preserved',(await page.locator('#project-detail').inputValue()).includes('Detalle conservado'));
 await page.getByRole('button',{name:'Guardar borrador',exact:true}).click();
 await step('Entrega y condiciones');
 await page.reload();
 await page.locator('#quote-step-2').waitFor({state:'visible'});
 check('Reload restores the selected step',true);
 await step('Proyecto y cliente');
 check('Reload restores draft client',(await page.locator('#client-name').inputValue())==='Cliente sintético de prueba wizard');
 await page.setViewportSize({width:390,height:844});
 await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
 await page.screenshot({path:resolve(out,'paso-1-mobile.png'),fullPage:true});
 check('Mobile page has no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 check('Inactive panels stay mounted and inert',await page.evaluate(()=>Array.from(document.querySelectorAll('.wizard-step')).filter(e=>e.hasAttribute('hidden')).every(e=>e.hasAttribute('inert'))));
 check('No uncaught page errors',errors.length===0);
 const report={status:'passed',scope:'Synthetic local UI, no quotations saved or provider calls made',origin,checks,errors};
 writeFileSync(resolve(out,'results.json'),JSON.stringify(report,null,2)+'\n');console.log(JSON.stringify(report));
} finally {await context.close();await browser.close();}
