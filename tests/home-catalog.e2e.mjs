import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdirSync,writeFileSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const origin=(process.env.E2E_ORIGIN||'http://127.0.0.1:3370').replace(/\/$/,'');
const require=createRequire(resolve(root,'web/package.json'));
const {chromium}=require('playwright');
const out=resolve(root,'tests/artifacts/home-catalog');mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true,...(process.env.E2E_BROWSER_CHANNEL?{channel:process.env.E2E_BROWSER_CHANNEL}:{})});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage();page.setDefaultTimeout(15000);
const results=[],errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto(origin+'/catalogo?seleccion=packs');
 const input=page.getByRole('searchbox',{name:'Buscar en esta categoría'});
 await input.fill('mini');
 await page.locator('.sweet-results-heading [role=status]').filter({hasText:'1 servicio'}).waitFor();
 const focused=await input.evaluate(e=>{const c=getComputedStyle(e),p=getComputedStyle(e.closest('.catalog-search'));return {inputOutline:c.outlineStyle,inputShadow:c.boxShadow,inputBorder:c.borderTopWidth,parentOutline:p.outlineStyle,parentShadow:p.boxShadow};});
 assert.equal(focused.inputOutline,'none');assert.equal(focused.inputShadow,'none');assert.equal(focused.inputBorder,'0px');assert.notEqual(focused.parentShadow,'none');
 results.push({name:'search filters packs with one focus indicator',focus:focused});
 await page.screenshot({path:resolve(out,'busqueda-desktop.png'),fullPage:false});
 await page.getByRole('button',{name:'Limpiar',exact:true}).click();
 await page.locator('.sweet-results-heading [role=status]').filter({hasText:'3 servicios'}).waitFor();
 results.push({name:'clear restores three services'});
 await page.goto(origin);
 const nav=page.getByRole('navigation',{name:'Principal'});
 assert.deepEqual(await nav.getByRole('link').allTextContents(),['Catálogo','Cómo Funciona','Accede']);
 const brandBox=await page.locator('header .sweet-wordmark').boundingBox(),navBox=await nav.boundingBox();
 assert.ok(brandBox&&navBox&&navBox.x>brandBox.x+brandBox.width&&navBox.x+navBox.width<=1440);
 results.push({name:'header has three right aligned navigation links'});
 const photos=await page.locator('main img').count();
 const wrapped=await page.locator('main img').evaluateAll(elements=>elements.every(e=>!!e.closest('button.image-presentation-trigger')));
 assert.ok(wrapped,'every home photograph must use a dialog trigger');
 results.push({name:'all home photos use dialogs',photos});
 const groups=['.sweet-hero-image','.sweet-runway-track .sweet-piece-open','.occasion-story-photo','.occasion-inspiration-grid .sweet-piece-open','.sweet-atelier-visual','.sweet-service-photo'];
 for(const selector of groups){
  const trigger=page.locator(selector).first();
  const before=page.url();
  await trigger.click();
  const dialog=page.getByRole('dialog');await dialog.waitFor({state:'visible'});
  assert.equal(page.url(),before);
  await dialog.getByRole('heading').first().waitFor();
  await page.keyboard.press('Escape');await dialog.waitFor({state:'hidden'});
  assert.ok(await trigger.evaluate(e=>document.activeElement===e),'focus must return to original photo');
  results.push({name:'dialog opens without navigation and returns focus',selector});
 }
 assert.equal(await page.getByText('Explorar presentación',{exact:true}).count(),0);
 assert.ok(await page.getByRole('link',{name:'Cotizar mi proyecto',exact:true}).count()<=2);
 results.push({name:'repeated presentation prompts removed; quote action limited to main section and footer'});
 await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
 await page.screenshot({path:resolve(out,'inicio-desktop.png'),fullPage:false});
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Abrir menú',exact:true}).click();
 assert.ok(await nav.getByRole('link',{name:'Accede',exact:true}).isVisible());
 await page.keyboard.press('Escape');
 assert.equal(await page.getByRole('button',{name:'Abrir menú',exact:true}).getAttribute('aria-expanded'),'false');
 await page.locator('.sweet-hero-image').click();await page.getByRole('dialog').waitFor();
 assert.ok(await page.getByRole('dialog').getByRole('heading').first().isVisible());
 await page.getByRole('dialog').evaluate(async element=>{await Promise.allSettled(element.getAnimations({subtree:true}).map(animation=>animation.finished));});
 await page.screenshot({path:resolve(out,'modal-mobile.png'),fullPage:false});
 await page.getByRole('button',{name:'Cerrar presentación',exact:true}).click();
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 results.push({name:'mobile menu and dialog are operable without horizontal overflow'});
 assert.deepEqual(errors,[]);
 const report={status:'passed',origin,checks:results,uncaughtErrors:errors};
 writeFileSync(resolve(out,'results.json'),JSON.stringify(report,null,2)+'\n');console.log(JSON.stringify(report));
}finally{await context.close();await browser.close();}
