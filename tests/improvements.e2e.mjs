import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {mkdirSync,writeFileSync,readFileSync} from 'node:fs';

const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const origin=process.env.E2E_ORIGIN||'http://127.0.0.1:3370';
assert.ok(/^http:\/\/(127\.0\.0\.1|localhost):\d+$/.test(origin),'This synthetic acceptance test is restricted to loopback');
const accounts=JSON.parse(readFileSync(process.env.E2E_CREDENTIALS_FILE||resolve(root,'.local/review-accounts.json'),'utf8'));
const customer=accounts.accounts.find(account=>account.role!=='admin'&&account.username&&account.password);
assert.ok(customer,'Private synthetic customer credentials required');
const require=createRequire(resolve(root,'web/package.json'));
const {chromium}=require('playwright');
const out=resolve(root,'tests/artifacts/improvements-ux');mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true,...(process.env.E2E_BROWSER_CHANNEL?{channel:process.env.E2E_BROWSER_CHANNEL}:{})});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage();page.setDefaultTimeout(25000);
await page.emulateMedia({reducedMotion:'reduce'});
const checks=[],errors=[];
page.on('pageerror',error=>errors.push(error.message));
const check=(name,value)=>{assert.ok(value,name);checks.push(name);};
const step=label=>page.getByRole('navigation',{name:'Pasos de la cotización'}).getByRole('button',{name:new RegExp(label)}).click();
const draft=()=>page.evaluate(()=>JSON.parse(sessionStorage.getItem('ea-pastry-draft')||'{}'));
const login=async()=>{
 await page.goto(origin+'/auth/login');
 await page.locator('input[name="username"]').fill(customer.username);
 await page.locator('input[name="password"]').fill(customer.password);
 await page.locator('form').getByRole('button',{name:/Entrar|Ingresar|Iniciar sesión|Acceder/}).click();
 await page.waitForURL(url=>url.pathname==='/cotizar');
 await page.locator('#client-document').waitFor({state:'visible'});
};
try {
 await login();
 check('Account credentials open the customer quotation wizard',new URL(page.url()).pathname==='/cotizar');
 check('Exactly four accessible wizard steps',await page.getByRole('navigation',{name:'Pasos de la cotización'}).getByRole('button').count()===4);
 check('Package chooser belongs to project step only',await page.locator('#quote-step-0 #package-heading').count()===1&&await page.locator('#quote-step-1 #package-heading').count()===0);
 check('New event package heading',await page.getByRole('heading',{name:'Elige el paquete para tu evento.',exact:true}).isVisible());
 check('Event date is mandatory',await page.locator('[data-field="eventDate"] input').getAttribute('required')!==null);
 await page.locator('#client-type').click();
 check('Only two client types are offered',await page.getByRole('option').count()===2);
 check('Natural person and company are the only choices',await page.getByRole('option').allTextContents().then(labels=>labels.join('|')==='Persona Natural|Empresa'));
 await page.getByRole('option',{name:'Persona Natural',exact:true}).click();
 await page.locator('#project-detail').fill('Evento sintético de aceptación visual. Selección y detalles para las pruebas locales.');
 await page.locator('#client-document').fill('12345678');
 await page.locator('#client-name').fill('Cliente sintético de aceptación visual');
 await page.locator('#business-phone').fill('900000000');
 const eventDate=new Date(Date.now()+10*86400000).toISOString().slice(0,10);
 await page.locator('[data-field="eventDate"] input').fill(eventDate);
 const text=await page.locator('#project-detail').boundingBox(),counter=await page.locator('.character-counter').boundingBox();
 check('Character counter is below the textbox at its left edge',!!text&&!!counter&&counter.y>=text.y+text.height-1&&Math.abs(counter.x-text.x)<3);
 for(const [objective,collection] of [['Empresas','Regalos corporativos'],['Proyecto a medida','Selección a medida'],['Lanzamientos de marca','Experiencias de marca'],['Bodas','Celebraciones privadas']]){
  await page.locator('#client-objective').click();await page.getByRole('option',{name:objective,exact:true}).click();
  await page.waitForFunction(title=>document.querySelector('.package-context h3')?.textContent===title,collection);
  check('Package context follows '+collection,await page.locator('#quote-step-0 .package-card').count()===3);
 }
 await page.waitForFunction(()=>JSON.parse(sessionStorage.getItem('ea-pastry-draft')||'{}').packageId==='custom');
 await step('Servicios e insumos');
 check('Package selection can be skipped',await page.locator('.empty-items').isVisible());
 check('Services step only has service and optional ingredient sections',await page.locator('#quote-step-1 .form-title h3').allTextContents().then(labels=>labels.length===2&&labels[0]==='Servicios de la propuesta'&&labels[1].startsWith('Ficha de insumos')));
 check('Portfolio has six representative entry categories',await page.locator('.portfolio-entry-categories button').count()===6);
 await step('Proyecto y cliente');
 const suggested=page.getByRole('button',{name:/^Sugerido para revisar:/});
 await suggested.click();
 const packageDialog=page.getByRole('dialog');
 check('Recommendation opens a detailed package popup',await packageDialog.locator('.package-detail-list article').count()>0);
 check('Popup lists product quantities and reference ingredients',await packageDialog.locator('.package-detail-list small').count()>0&&await packageDialog.getByRole('heading',{name:'Insumos y personalización'}).isVisible());
 check('Preview leaves package and services unchanged',(await draft()).packageId==='custom'&&(await draft()).items.length===0);
 await page.keyboard.press('Escape');
 await packageDialog.waitFor({state:'hidden'});
 check('Closing package popup restores keyboard focus',await suggested.evaluate(el=>document.activeElement===el));
 await suggested.click();await page.getByRole('dialog').getByRole('button',{name:'Elegir este paquete',exact:true}).click();
 await page.waitForFunction(()=>JSON.parse(sessionStorage.getItem('ea-pastry-draft')||'{}').packageId!=='custom');
 check('Package is only loaded after explicit confirmation',(await draft()).items.length>0);
 await page.screenshot({path:resolve(out,'paso-1-desktop.png'),fullPage:true});
 await step('Servicios e insumos');
 await page.getByRole('button',{name:'Tortas y postres',exact:true}).click();
 await page.getByRole('dialog').getByRole('button',{name:/^Personalizar /}).first().click();
 const serviceDialog=page.getByRole('dialog');
 check('Ten accepted flavors offered',await serviceDialog.locator('input[name="flavors"]').count()===10);
 const flavors=serviceDialog.locator('input[name="flavors"]');
 for(let index=0;index<4;index++)await flavors.nth(index).check();
 check('Fifth flavor disabled after four selections',await flavors.nth(4).isDisabled());
 check('Price and sale unit cannot be edited',await serviceDialog.locator('input[name="priceCents"]').getAttribute('readonly')!==null&&await serviceDialog.locator('input[name="unit"]').getAttribute('readonly')!==null);
 await serviceDialog.getByRole('button',{name:'Añadir a la propuesta',exact:true}).click();
 check('Missing presentation prevents adding service',await serviceDialog.isVisible()&&await serviceDialog.locator('[role="alert"]').isVisible());
 await serviceDialog.locator('textarea[name="presentation"]').fill('Caja de muestra para pruebas');
 await serviceDialog.locator('input[name="quantity"]').fill('2');
 await serviceDialog.getByRole('button',{name:'Añadir a la propuesta',exact:true}).click();
 await serviceDialog.waitFor({state:'hidden'});
 await page.waitForFunction(()=>JSON.parse(sessionStorage.getItem('ea-pastry-draft')||'{}').items.some(item=>item.portfolioId));
 const portfolio=(await draft()).items.find(item=>item.portfolioId);
 check('Blank optional scope stored as Unknown.',portfolio.scope==='Unknown.'&&portfolio.description.includes('Unknown.'));
 check('Four flavors and user quantity retained',portfolio.flavors.length===4&&portfolio.quantity===2);
 await page.screenshot({path:resolve(out,'paso-2-desktop.png'),fullPage:true});
 await step('Entrega y condiciones');
 check('Delivery and conditions have the three requested sections',await page.locator('#quote-step-2 .form-title h3').allTextContents().then(labels=>labels.join('|')==='Locación y movilidad|Vigencia e impuestos|Condiciones y notas'));
 check('Deposit cannot be edited in delivery step',await page.locator('#quote-step-2 [data-field="advancePercent"] input').count()===0);
 check('Fifty percent deposit is explained',await page.locator('.wizard-total').innerText().then(text=>text.includes('50%')));
 const issued=await page.locator('[data-field="issued"] input').boundingBox(),valid=await page.locator('[data-field="validUntil"] input').boundingBox();
 check('Validity dates share one desktop row',!!issued&&!!valid&&Math.abs(issued.y-valid.y)<3);
 await page.screenshot({path:resolve(out,'paso-3-desktop.png'),fullPage:true});
 await step('Proyecto y cliente');
 await page.setViewportSize({width:390,height:844});
 await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
 check('Mobile wizard has no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 const mobileText=await page.locator('#project-detail').boundingBox(),mobileCounter=await page.locator('.character-counter').boundingBox();
 check('Mobile counter remains below left',!!mobileText&&!!mobileCounter&&mobileCounter.y>=mobileText.y+mobileText.height-1&&Math.abs(mobileCounter.x-mobileText.x)<3);
 await page.screenshot({path:resolve(out,'paso-1-mobile.png'),fullPage:true});
 await page.getByRole('button',{name:/^Sugerido para revisar:/}).click();
 check('Mobile package popup stays within viewport',await page.getByRole('dialog').evaluate(el=>{const rect=el.getBoundingClientRect();return rect.left>=0&&rect.right<=innerWidth+1&&rect.top>=0&&rect.bottom<=innerHeight+1;}));
 await page.screenshot({path:resolve(out,'paquete-mobile.png'),fullPage:true});
 await page.keyboard.press('Escape');
 check('No uncaught browser errors',errors.length===0);
 const report={status:'passed',scope:'Synthetic isolated browser context; drafts only, no saved quotes, no external mail or provider calls',origin,checks,errors};
 writeFileSync(resolve(out,'report.json'),JSON.stringify(report,null,2));
 console.log(JSON.stringify({status:'passed',checks:checks.length,report:resolve(out,'report.json')}));
} catch(error){
 await page.screenshot({path:resolve(out,'failure.png'),fullPage:true}).catch(()=>{});
 writeFileSync(resolve(out,'report.json'),JSON.stringify({status:'failed',scope:'Synthetic browser context',origin,checks,errors,error:error.message},null,2));
 throw error;
} finally {await context.close();await browser.close();}
